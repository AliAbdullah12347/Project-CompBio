#!/usr/bin/env python3
"""Emit one Volcano job per group of rows, one row per pod.

The 8 Nov run packed five or six rows onto each of six pods behind a 3 h
per-row `timeout`, and lost 19 of them to that timeout. The arithmetic was
never going to work: the cluster's validating policy caps a job at 24 CPU, so
6 pods x 4 CPU is one job's entire parallelism, and 31 rows through 6 pods is
five rows deep per pod.

Jobs are the thing that scales here. The burst quota allows 200 pods and 50
jobs with no CPU ceiling of its own, so N jobs of six pods put 6N rows on the
cluster at once. One row per pod, five jobs, and every row gets the whole 24 h
window to itself instead of a 3 h slice of a shared pod.

An entry may chain rows with '+' when a later row reads an earlier one's
output: comm-039 reads comm-038, bmind-047 reads bmind-046, hub-037 reads
hub-036. The 8 Nov static deal scattered those across pods and every dependent
exited status=1 within seconds of starting. Chained rows share a pod, run in
order, and split the pod's time budget.

    python network/cluster/mkjobs.py            # write the yaml, submit nothing
    python network/cluster/mkjobs.py --submit   # write and kubectl create
"""
import argparse
import os
import subprocess

PODS_PER_JOB = 6          # 6 x 4 CPU hits the 24-CPU per-job ceiling exactly
CPU = 4
MEM = "22Gi"
DEADLINE = 86400          # 24 h, the burst ceiling on the cpu queue
OUT = "network/cluster/generated"

# Rows that timed out on 8 Nov. Each left per-draw checkpoints in S3 and each
# script skips draws whose checkpoint exists, so these resume rather than
# restart: gene-025 has 18 of its 20 draws done, mod-013 has 8.
HEAVY = """ref-002 ref-004 corr-006 pow-010 pow-011 pow-012
           mod-013 mod-014 mod-015 mod-016 mod-017 mod-018 mod-019 mod-020
           gene-025 gene-026 gene-028 gene-029 perm-032""".split()

# Rows that errored within seconds and are now fixed, plus cent-040, whose pod
# was killed before it got there. In each chained pair the first row is already
# complete; it re-runs only far enough to find its checkpoints and exit.
LIGHT = ["net-008", "inp-024", "comm-038+comm-039", "cent-040",
         "filt-044", "tob-045", "bmind-046+bmind-047", "hub-036+hub-037"]

TEMPLATE = """# GENERATED by network/cluster/mkjobs.py - edit the generator, not this file.
#
# {name}: {n} pods, one entry each.
#   {rowlist}
apiVersion: batch.volcano.sh/v1alpha1
kind: Job
metadata:
  name: {name}
spec:
  queue: cpu
  priorityClassName: burst
  ttlSecondsAfterFinished: 604800
  tasks:
    - name: main
      replicas: {n}
      template:
        spec:
          restartPolicy: Never
          activeDeadlineSeconds: {deadline}
          securityContext:
            runAsNonRoot: true
            runAsUser: 1000
            seccompProfile: {{type: RuntimeDefault}}
          volumes:
            - name: work
              emptyDir: {{sizeLimit: 24Gi}}
            - name: s3-ca
              configMap: {{name: s3-ca}}
          containers:
            - name: main
              image: bioconductor/bioconductor_docker:RELEASE_3_20
              workingDir: /work
              envFrom: [{{secretRef: {{name: s3-credentials}}}}]
              env:
                - {{name: HOME,            value: /work}}
                - {{name: R_LIBS_USER,     value: /work/rlibs}}
                - {{name: AWS_CA_BUNDLE,   value: /etc/s3-ca/ca-bundle.pem}}
                - {{name: BUCKET,          value: aabdullah-lithium-bipolar-project-fall-2026}}
                - {{name: PREFIX,          value: network/arm3}}
                - {{name: CPU_LIMIT,       value: "{cpu}"}}
                - {{name: OMP_NUM_THREADS, value: "{cpu}"}}
                - {{name: ROWS,            value: "{rows}"}}
                - name: POD_NAME
                  valueFrom: {{fieldRef: {{fieldPath: metadata.name}}}}
              volumeMounts:
                - {{name: work,  mountPath: /work}}
                - {{name: s3-ca, mountPath: /etc/s3-ca, readOnly: true}}
              resources:
                requests: {{cpu: "1", memory: 8Gi}}
                limits:   {{cpu: "{cpu}", memory: {mem}}}
              securityContext:
                allowPrivilegeEscalation: false
                capabilities: {{drop: [ALL]}}
              command: ["bash", "-lc"]
              args:
                - |
                  set -euo pipefail
                  START=$(date +%s)
                  IDX="${{POD_NAME##*-}}"
                  mkdir -p /work/rlibs /work/out
                  LOG="/work/out/{name}-${{IDX}}.log"
                  exec > >(tee -a "$LOG") 2>&1
                  echo "== $(date -u) {name} pod ${{IDX}} =="

                  # One entry per pod; '+' chains dependent rows onto that pod.
                  ENTRY=$(echo "$ROWS" | tr ' ' '\\n' | sed -n "$((IDX + 1))p")
                  if [ -z "$ENTRY" ]; then echo "-- no entry for pod ${{IDX}}"; exit 0; fi
                  MINE=$(echo "$ENTRY" | tr '+' ' ')
                  echo "-- entry: $ENTRY"

                  git clone --filter=blob:none --no-checkout --depth 1 \\
                    https://github.com/AliAbdullah12347/Project-CompBio.git /work/repo
                  cd /work/repo
                  git sparse-checkout init --no-cone
                  git sparse-checkout set "/data/analysis_matrices/*" "/data/LM22.txt" \\
                    "/de_analysis/data/*" "/de_analysis/scripts/*" "/network/*" \\
                    "/de_v2/scripts/*" "/de_final/results/*"
                  git checkout
                  mkdir -p network/cache network/runs
                  source network/cluster/lib.sh
                  trap 's3_put "$LOG" logs/{name}-'"${{IDX}}"'.log || true' EXIT

                  setup_r
                  fetch_cache
                  fetch_counts || echo "-- no raw counts; only filt-044 needs them"
                  write_rprofile "$CPU_LIMIT"

                  # Keep 15 min at the end for the final upload, and split what
                  # remains evenly between the rows chained onto this pod.
                  NROWS=$(echo $MINE | wc -w)
                  BUDGET=$(( {deadline} - ($(date +%s) - START) - 900 ))
                  CAP=$(( BUDGET / NROWS ))
                  echo "-- $NROWS row(s), ${{CAP}}s each out of ${{BUDGET}}s left"

                  for id in $MINE; do
                    echo "=== $id cap=${{CAP}}s $(date -u) ==="
                    T0=$(date +%s)
                    mkdir -p "network/runs/$id"
                    restore_run "$id"
                    set +e
                    timeout "$CAP" Rscript "network/experiments/$id.R" "$id" \\
                      >> "network/runs/$id/log.txt" 2>&1
                    RC=$?
                    set -e
                    echo "$id rc=$RC secs=$(( $(date +%s) - T0 ))" \\
                      | tee -a /work/out/status-${{IDX}}.tsv
                    tail -3 "network/runs/$id/log.txt" || true
                    upload_run "$id" || true
                  done
                  s3_put /work/out/status-${{IDX}}.tsv "status/{name}-${{IDX}}.tsv" || true
                  echo "== $(date -u) pod ${{IDX}} done =="
"""


def groups(entries, k):
    return [entries[i:i + k] for i in range(0, len(entries), k)]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--submit", action="store_true")
    ap.add_argument("--only", help="space-separated entries instead of HEAVY+LIGHT")
    ap.add_argument("--start", type=int, default=1, help="first job number")
    a = ap.parse_args()
    os.makedirs(OUT, exist_ok=True)
    entries = a.only.split() if a.only else HEAVY + LIGHT
    files = []
    for i, g in enumerate(groups(entries, PODS_PER_JOB), start=a.start):
        name = "arm3-run-%02d" % i
        path = os.path.join(OUT, name + ".yaml")
        with open(path, "w", newline="\n") as fh:
            fh.write(TEMPLATE.format(name=name, n=len(g), rows=" ".join(g),
                                     rowlist="\n#   ".join(g), cpu=CPU,
                                     mem=MEM, deadline=DEADLINE))
        files.append(path)
        print("%-12s %d pods  %s" % (name, len(g), " ".join(g)))
    print("\n%d entries -> %d jobs, %d pods, %d CPU in all" %
          (len(entries), len(files), len(entries), len(entries) * CPU))
    if a.submit:
        for p in files:
            print("\n$ kubectl create -f " + p)
            subprocess.run(["kubectl", "create", "-f", p], check=True)


if __name__ == "__main__":
    main()
